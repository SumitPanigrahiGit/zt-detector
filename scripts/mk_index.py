"""mk_index.py - builds docs/results-index.md by copying lines from result files."""
import re, sys

# (section, claim, file, regex of lines to copy, status, caveat)
ITEMS = [
 ("4.1", "Idle and heavy-load loader CPU, per-event cost (last runs)", "docs/bench-results.txt",
  r"Loader CPU|eBPF programs", "measured", "WSL2, noisy; counters accumulate across runs; bench.sh without -c"),
 ("4.2", "Detection with rate and age features, 5 seeds", "docs/results-day35-fresh.txt",
  r"flagged", "measured", "seeds not independent; beacon/scan/wx include unseen tokens"),
 ("4.2", "Before the age feature (burst missed)", "docs/results-day34-before-age.txt",
  r"flagged", "measured", "same data, earlier feature set"),
 ("4.3", "Real vs proxy container age on running containers", "docs/results-day36-pre-real.txt",
  r"flagged", "measured", "short recordings; 5 seeds not independent"),
 ("4.3", "Proxy age, same test", "docs/results-day36-pre-proxy.txt",
  r"flagged", "measured", "compare with the real-age row"),
 ("4.4", "Nginx-only vs nginx+redis model", "docs/results-day37.txt",
  r"flagged", "measured", "attacks only on the nginx image"),
 ("4.4", "Per-service baselines", "docs/results-day38.txt",
  r"flagged", "measured", "service chosen from container names"),
 ("4.4", "Poisoning and jitter (L=12)", "docs/results-day41.txt",
  r"flagged", "measured", "2 poisoned recordings; one workload"),
 ("5", "Rule B vs rule A threshold", "docs/results-day42.txt",
  r"rule A", "hypothesis failed", "identical counts; 4 held-out windows per run"),
 ("4.5", "Freeze time by method", "docs/results-day43-freeze.txt",
  r"median", "measured", "20 runs each; request until kernel reports frozen=1; action only"),
 ("4.5", "Two-window rule at 10 s", "docs/results-day43-replay.txt",
  r"normal windows|recordings detected", "measured", "cost 9 burst detections, removed no false alarms"),
 ("4.5", "Live latency, 10 s windows", "docs/results-day45.txt",
  r"^\d ", "measured", "8 runs; one scripted attack; latency set by window phase"),
 ("5", "5 s windows offline", "docs/results-day46-fp.txt",
  r"normal windows|recordings detected", "measured", "4 flags are 2 distinct windows"),
 ("5", "5 s windows live, L=12", "docs/results-day47-live5.txt",
  r"^\d ", "hypothesis failed", "normal client flagged in 4 of 6 runs"),
 ("5", "5 s windows live, L=24", "docs/results-day48-L24.txt",
  r"^\d ", "hypothesis failed", "1 of 6 runs flagged the normal client"),
 ("5", "5 s, L=24, two in a row", "docs/results-day49-consec2.txt",
  r"^\d ", "measured", "sudo expired mid-run; run valid but suspect"),
 ("4.5", "Live latency, API test", "docs/results-day51.txt",
  r"GET|unfreeze|before|after", "measured", "tiny log; one throwaway container"),
]

out = ["# Results index (generated by scripts/mk_index.py; do not edit by hand)\n"]
missing = 0
for sec, claim, path, pat, status, caveat in ITEMS:
    out.append("## %s  %s\n- source: `%s`\n- status: **%s**\n- caveat: %s\n" % (sec, claim, path, status, caveat))
    try:
        lines = [l.rstrip() for l in open(path) if re.search(pat, l)]
    except OSError:
        lines = []
    if not lines:
        missing += 1
        out.append("- MISSING: no matching lines\n")
    else:
        out.append("```\n" + "\n".join(lines[:14]) + "\n```\n")
open("docs/results-index.md", "w").write("\n".join(out))
print("items:", len(ITEMS), "missing:", missing)
sys.exit(1 if missing else 0)
